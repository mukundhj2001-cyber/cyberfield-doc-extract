"""Generate fictional sample documents into ./samples (PDF invoices/receipt/resumes + a PNG receipt)."""
from pathlib import Path
from reportlab.lib.pagesizes import A4
from reportlab.lib.colors import HexColor
from reportlab.pdfgen import canvas
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parents[1] / "samples"; OUT.mkdir(exist_ok=True)
GOLD, INK = HexColor("#B8901F"), HexColor("#111111")


def money(v, cur):
    return f"{cur}{v:,.2f}"


def invoice(fname, vendor, addr, gstin, number, date, due, bill_to, items, tax_label, tax_rate, cur, total_override=None):
    c = canvas.Canvas(str(OUT / fname), pagesize=A4); w, h = A4
    c.setFillColor(GOLD); c.rect(0, h - 18, w, 18, fill=1, stroke=0)
    c.setFillColor(INK); c.setFont("Helvetica-Bold", 20); c.drawString(50, h - 70, vendor)
    c.setFont("Helvetica", 10)
    for i, l in enumerate(addr + ([f"GSTIN: {gstin}"] if gstin else [])): c.drawString(50, h - 88 - i * 13, l)
    c.setFont("Helvetica-Bold", 24); c.setFillColor(GOLD); c.drawRightString(w - 50, h - 70, "TAX INVOICE" if gstin else "INVOICE")
    c.setFillColor(INK); c.setFont("Helvetica", 10)
    c.drawRightString(w - 50, h - 92, f"Invoice No: {number}")
    c.drawRightString(w - 50, h - 105, f"Invoice Date: {date}")
    c.drawRightString(w - 50, h - 118, f"Due Date: {due}")
    y = h - 170
    c.setFont("Helvetica-Bold", 10); c.drawString(50, y, "Bill To:"); c.setFont("Helvetica", 10)
    for i, l in enumerate(bill_to): c.drawString(50, y - 14 - i * 13, l)
    y -= 90
    c.setFillColor(HexColor("#F3EAD0")); c.rect(45, y - 6, w - 90, 20, fill=1, stroke=0); c.setFillColor(INK)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(50, y, "Description"); c.drawRightString(360, y, "Qty"); c.drawRightString(450, y, "Unit Price"); c.drawRightString(w - 50, y, "Amount")
    c.setFont("Helvetica", 10); sub = 0
    for d, q, p in items:
        y -= 22; amt = q * p; sub += amt
        c.drawString(50, y, d); c.drawRightString(360, y, str(q)); c.drawRightString(450, y, money(p, cur)); c.drawRightString(w - 50, y, money(amt, cur))
    tax = round(sub * tax_rate, 2); total = total_override if total_override is not None else sub + tax
    y -= 40
    for lab, v, bold in [("Subtotal", sub, False), (f"{tax_label} ({tax_rate*100:g}%)", tax, False), ("Total", total, True)]:
        c.setFont("Helvetica-Bold" if bold else "Helvetica", 12 if bold else 10)
        c.drawRightString(450, y, lab + ":"); c.drawRightString(w - 50, y, money(v, cur)); y -= 18
    c.setFont("Helvetica-Oblique", 9); c.setFillColor(HexColor("#666666"))
    c.drawString(50, 60, "Thank you for your business. Payment terms: Net 15. Fictional sample document generated by Cyberfield AI.")
    c.save()


def receipt_pdf():
    w, h = 226, 520
    c = canvas.Canvas(str(OUT / "receipt_cafe_aroma.pdf"), pagesize=(w, h))
    y = h - 30
    def line(t, font="Courier", size=8.5, center=False):
        nonlocal y
        c.setFont(font, size); (c.drawCentredString(w / 2, y, t) if center else c.drawString(14, y, t)); y -= 13
    line("CAFE AROMA", "Courier-Bold", 13, True); line("21 Brigade Road, Bengaluru", center=True); line("Ph: 080 4000 1234", center=True)
    line("-" * 38); line("Receipt #: CA-558213"); line("Date: 12/10/2026  Time: 18:42"); line("Cashier: Ritu"); line("-" * 38)
    items = [("Cappuccino", 2, 180.0), ("Blueberry Muffin", 1, 145.0), ("Paneer Sandwich", 1, 220.0), ("Cold Brew", 1, 210.0)]
    sub = 0
    for d, q, p in items:
        amt = q * p; sub += amt; line(f"{q} x {d:<18}{amt:>9.2f}")
    tax = round(sub * 0.05, 2); line("-" * 38)
    line(f"{'Subtotal':<26}{sub:>10.2f}"); line(f"{'GST 5%':<26}{tax:>10.2f}"); line(f"{'TOTAL':<26}{sub + tax:>10.2f}", "Courier-Bold", 9.5)
    line("Paid by: UPI"); line("-" * 38); line("Thank you! Visit again.", center=True); line("Fictional sample by Cyberfield AI", size=6.5, center=True)
    c.save()


def receipt_png():
    img = Image.new("RGB", (560, 900), "white"); d = ImageDraw.Draw(img)
    try:
        f = ImageFont.truetype("DejaVuSansMono.ttf", 22); fb = ImageFont.truetype("DejaVuSansMono-Bold.ttf", 30)
    except OSError:
        f = fb = ImageFont.load_default()
    y = 30
    def line(t, font=None, center=False):
        nonlocal y
        font = font or f
        x = (560 - d.textlength(t, font=font)) / 2 if center else 30
        d.text((x, y), t, fill="black", font=font); y += 38
    line("FRESHMART GROCERY", fb, True); line("88 Anna Salai, Chennai", center=True); line("-" * 34)
    line("Receipt No: FM-20931"); line("Date: 2026-10-08 11:15"); line("-" * 34)
    items = [("Basmati Rice 5kg", 1, 649.0), ("Toor Dal 1kg", 2, 165.0), ("Milk 1L", 3, 62.0), ("Bananas 1 dozen", 1, 70.0)]
    sub = 0
    for n, q, p in items:
        amt = q * p; sub += amt; line(f"{q} x {n:<17}{amt:>9.2f}")
    line("-" * 34); line(f"{'Subtotal':<22}{sub:>10.2f}"); line(f"{'Tax':<22}{0:>10.2f}"); line(f"{'TOTAL':<22}{sub:>10.2f}", fb); line("Paid by: Card")
    img.save(OUT / "receipt_freshmart.png")


def resume(fname, name, title, contact, summary, skills, jobs, edu):
    c = canvas.Canvas(str(OUT / fname), pagesize=A4); w, h = A4
    c.setFont("Helvetica-Bold", 24); c.setFillColor(INK); c.drawString(50, h - 70, name)
    c.setFont("Helvetica", 12); c.setFillColor(GOLD); c.drawString(50, h - 90, title)
    c.setFillColor(INK); c.setFont("Helvetica", 9.5); c.drawString(50, h - 108, "  |  ".join(contact))
    y = h - 140
    def section(t):
        nonlocal y
        c.setFont("Helvetica-Bold", 12); c.setFillColor(GOLD); c.drawString(50, y, t.upper()); c.setFillColor(INK)
        c.line(50, y - 4, w - 50, y - 4); y -= 22
    def text(t, font="Helvetica", size=10):
        nonlocal y
        c.setFont(font, size); c.drawString(50, y, t); y -= 14
    section("Summary"); text(summary); y -= 8
    section("Skills"); text(", ".join(skills)); y -= 8
    section("Experience")
    for role, co, dates, bullets in jobs:
        text(f"{role} - {co}", "Helvetica-Bold"); text(dates, "Helvetica-Oblique", 9.5)
        for b in bullets: text(f"- {b}")
        y -= 6
    section("Education")
    for e in edu: text(e)
    c.save()


